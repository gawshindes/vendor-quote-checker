'use strict';
/*
 * Builds the PDF report attached to the review email. Letter size, one column,
 * the same type and colors as the blog (charcoal on white, neutral grays).
 */
const fs = require('node:fs');
const path = require('node:path');
const PDFDocument = require('pdfkit');
const { config } = require('./config');

const C = { ink: '#111111', body: '#333333', muted: '#666666', line: '#E5E5E5', flag: '#9A3412', accent: '#111111', evid: '#444444' };
const PAGE = { w: 612, h: 792, m: 60 };
const W = PAGE.w - PAGE.m * 2;

const AREA = { scope: 'Scope', missing_items: 'Missing items', pricing: 'Pricing', timeline: 'Timeline', change_control: 'Change control', acceptance: 'Acceptance and quality', ownership: 'Ownership and access', exit: 'Exit and handover', team: 'Team and delivery', technical_approach: 'Technical approach', ongoing_costs: 'Ongoing costs' };
const PRICING = { fixed: 'Appears to be a fixed price', time_and_materials: 'Appears to be time and materials', retainer: 'Appears to be a retainer', mixed: 'Appears to be a mix of models', unclear: 'Not clear from the document' };

/* Keep text within what the embedded fonts can draw. */
function clean(s) {
  return String(s || '')
    .replace(/[\u2010-\u2013]/g, '-').replace(/\u2014/g, ', ')
    .replace(/→/g, '->').replace(/≤/g, '<=').replace(/≥/g, '>=').replace(/ /g, ' ')
    .replace(/[^\u0009\u000A -ÿŒœ‘-„•…€™]/g, '');
}

function registerFonts(doc) {
  const f = (file) => path.join(config.paths.fonts, file);
  const fonts = {
    serif: ['newsreader-latin-400-normal.woff', 'Times-Roman'],
    serifMed: ['newsreader-latin-500-normal.woff', 'Times-Bold'],
    sans: ['schibsted-grotesk-latin-400-normal.woff', 'Helvetica'],
    sansBold: ['schibsted-grotesk-latin-600-normal.woff', 'Helvetica-Bold'],
  };
  for (const [name, [file, fallback]] of Object.entries(fonts)) {
    try {
      if (!fs.existsSync(f(file))) throw new Error('missing');
      doc.registerFont(name, f(file));
      doc.font(name).widthOfString('Test'); // fails here if the font file cannot be used
    } catch {
      doc.registerFont(name, fallback);
    }
  }
  doc.font('sans');
}

function formatDate(d) {
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'America/New_York' });
}

function buildReportPdf(review, meta) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margins: { top: PAGE.m, bottom: PAGE.m + 18, left: PAGE.m, right: PAGE.m }, bufferPages: true, info: { Title: `Vendor quote review: ${clean(meta.fileName)}`, Author: `${config.brand.aiName} by ${config.brand.ownerName}` } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    registerFonts(doc);

    const bottom = () => doc.page.height - doc.page.margins.bottom;
    const ensure = (h) => { if (doc.y + h > bottom()) doc.addPage(); };
    const rule = (color = C.line, width = 0.75) => {
      doc.save().moveTo(PAGE.m, doc.y).lineTo(PAGE.m + W, doc.y).lineWidth(width).strokeColor(color).stroke().restore();
    };
    const para = (text, { font = 'sans', size = 10.5, color = C.body, gap = 4, width = W, x = PAGE.m, lineGap = 2.5 } = {}) => {
      doc.font(font).fontSize(size).fillColor(color).text(clean(text), x, doc.y, { width, lineGap });
      doc.moveDown(gap / size);
    };
    const h2 = (text, intro) => {
      ensure(intro ? 140 : 100); // keep a heading with the start of its section
      doc.moveDown(1.2);
      para(text, { font: 'serif', size: 17, color: C.ink, gap: 3 });
      if (intro) para(intro, { size: 9.5, color: C.muted, gap: 10 });
    };

    /* Header */
    doc.y = PAGE.m;
    doc.font('serif').fontSize(15).fillColor(C.ink).text(clean(config.brand.aiName), PAGE.m, PAGE.m, { continued: true })
      .font('sans').fontSize(9).fillColor(C.muted).text(`  by ${clean(config.brand.ownerName)}`);
    doc.font('sans').fontSize(9).fillColor(C.muted).text(`Vendor quote review · ${formatDate(meta.date || new Date())}`, PAGE.m, PAGE.m + 5, { width: W, align: 'right' });
    doc.y = PAGE.m + 26;
    rule(C.ink);
    doc.moveDown(1.6);

    /* Summary */
    para(review.summary.headline, { font: 'serif', size: 22, color: C.ink, gap: 8, lineGap: 1 });
    const size = meta.businessSize === 'Midsize business' ? 'midsize' : 'small';
    const who = meta.role === 'Business owner' ? `a ${size} business owner` : meta.role === 'Manager' ? `a manager at a ${size} business` : `a reader at a ${size} business`;
    para(`Review of ${meta.fileName} · ${meta.pages} ${meta.pages === 1 ? 'page' : 'pages'} · Generated by ${config.brand.aiName} for ${who}`, { size: 8.5, color: C.muted, gap: 12 });
    if (review.summary.overview) para(review.summary.overview, { size: 11, gap: 14, lineGap: 3 });

    /* Key facts */
    const facts = [
      ['Vendor', review.vendor_name],
      ['Price', review.price_summary.total],
      ['Pricing model', PRICING[review.price_summary.pricing_model]],
      ['Payment terms', review.price_summary.payment_terms],
      ['Being delivered', review.project_summary],
    ].filter(([, v]) => v);
    if (review.is_reviewable && facts.length) {
      ensure(60);
      para('KEY FACTS AS STATED IN THE DOCUMENT', { font: 'sansBold', size: 8, color: C.muted, gap: 5 });
      rule(C.ink);
      for (const [k, v] of facts) {
        doc.font('sans').fontSize(10);
        const h = Math.max(doc.heightOfString(clean(v), { width: W - 120, lineGap: 2 }), 12) + 12;
        ensure(h);
        const y = doc.y + 6;
        doc.fillColor(C.muted).text(k, PAGE.m, y, { width: 110 });
        doc.fillColor(C.ink).text(clean(v), PAGE.m + 120, y, { width: W - 120, lineGap: 2 });
        doc.y = y + h - 6;
        rule();
      }
    }

    if (review.is_reviewable) {
      const flags = review.items.filter((i) => i.type === 'red_flag');
      const suggs = review.items.filter((i) => i.type !== 'red_flag');

      h2('Possible red flags', 'Points that may affect cost or control of your systems. You may want to discuss these with the vendor before you decide.');
      if (!flags.length) para('I did not find any possible red flags in this document.', { gap: 6 });
      for (const it of flags) {
        const pad = 12, iw = W - pad * 2;
        const label = clean(`POSSIBLE RED FLAG · ${(AREA[it.area] || '').toUpperCase()}`);
        doc.font('sansBold').fontSize(7.5); const h1 = doc.heightOfString(label, { width: iw });
        doc.font('serifMed').fontSize(12.5); const h2t = doc.heightOfString(clean(it.title), { width: iw });
        doc.font('sans').fontSize(10); const h3 = doc.heightOfString(clean(it.detail), { width: iw, lineGap: 2 });
        doc.font('sans').fontSize(8.5); const h4 = doc.heightOfString(clean(`In the document: ${it.evidence}`), { width: iw, lineGap: 1.5 });
        const boxH = pad + h1 + 4 + h2t + 4 + h3 + 6 + h4 + pad;
        ensure(boxH + 10);
        const top = doc.y;
        doc.save().rect(PAGE.m, top, W, boxH).lineWidth(0.75).strokeColor(C.flag).stroke().restore();
        let y = top + pad;
        doc.font('sansBold').fontSize(7.5).fillColor(C.flag).text(label, PAGE.m + pad, y, { width: iw, characterSpacing: 0.4 }); y += h1 + 4;
        doc.font('serifMed').fontSize(12.5).fillColor(C.ink).text(clean(it.title), PAGE.m + pad, y, { width: iw }); y += h2t + 4;
        doc.font('sans').fontSize(10).fillColor(C.body).text(clean(it.detail), PAGE.m + pad, y, { width: iw, lineGap: 2 }); y += h3 + 6;
        doc.font('sans').fontSize(8.5).fillColor(C.evid).text(clean(`In the document: ${it.evidence}`), PAGE.m + pad, y, { width: iw, lineGap: 1.5 });
        doc.y = top + boxH + 10;
      }

      if (suggs.length) {
        h2('Suggestions to consider', 'Points you may want to clarify or add to the agreement.');
        for (const it of suggs) {
          doc.font('serifMed').fontSize(12.5); const ht = doc.heightOfString(clean(it.title), { width: W });
          doc.font('sans').fontSize(10); const hd = doc.heightOfString(clean(it.detail), { width: W, lineGap: 2 });
          ensure(ht + hd + 50);
          para(`SUGGESTION · ${(AREA[it.area] || '').toUpperCase()}`, { font: 'sansBold', size: 7.5, color: C.accent, gap: 3 });
          para(it.title, { font: 'serifMed', size: 12.5, color: C.ink, gap: 3 });
          para(it.detail, { size: 10, gap: 4 });
          para(`In the document: ${it.evidence}`, { font: 'sans', size: 8.5, color: C.evid, gap: 8, lineGap: 1.5 });
          rule();
          doc.moveDown(0.6);
        }
      }

      if (review.questions_to_send.length) {
        h2('Questions you could ask the vendor', 'Written so you can paste them into an email if they are useful.');
        review.questions_to_send.forEach((q, i) => {
          doc.font('sans').fontSize(10.5);
          const h = doc.heightOfString(clean(q), { width: W - 22, lineGap: 2.5 });
          ensure(h + 8);
          const y = doc.y;
          doc.fillColor(C.muted).text(`${i + 1}.`, PAGE.m, y, { width: 18 });
          doc.fillColor(C.body).text(clean(q), PAGE.m + 22, y, { width: W - 22, lineGap: 2.5 });
          doc.y = y + h + 6;
        });
      }

      if (review.ongoing_costs_to_ask_about.length) {
        h2('Ongoing costs you may want to ask about');
        for (const c of review.ongoing_costs_to_ask_about) {
          doc.font('sans').fontSize(10.5);
          const h = doc.heightOfString(clean(c), { width: W - 16, lineGap: 2 });
          ensure(h + 6);
          const y = doc.y;
          doc.fillColor(C.muted).text('•', PAGE.m + 2, y);
          doc.fillColor(C.body).text(clean(c), PAGE.m + 16, y, { width: W - 16, lineGap: 2 });
          doc.y = y + h + 4;
        }
      }
    }

    if (review.limitations) {
      h2('What this review could not check');
      para(review.limitations, { gap: 6 });
    }

    /* Disclaimer */
    const disclaimer = `This review is for information only. It is not legal, financial or professional advice, and it does not recommend whether to sign or hire. It was generated by ${config.brand.aiName}, an AI model, from the document you provided, reflects only what could be found in that document, and may contain mistakes or miss terms that are there. Have a lawyer review any contract before you sign.`;
    doc.font('sans').fontSize(9);
    const dh = doc.heightOfString(clean(disclaimer), { width: W - 24, lineGap: 2 }) + 22;
    doc.moveDown(1.4);
    ensure(dh + 110);
    const dTop = doc.y;
    doc.save().rect(PAGE.m, dTop, W, dh).lineWidth(0.75).strokeColor(C.line).stroke().restore();
    doc.fillColor(C.evid).text(clean(disclaimer), PAGE.m + 12, dTop + 11, { width: W - 24, lineGap: 2 });
    doc.y = dTop + dh + 22;

    /* More reading */
    const notesUrl = `${config.brand.siteUrl}/blog/cto-notes/`;
    rule(C.ink);
    doc.moveDown(0.9);
    const cTop = doc.y;
    doc.font('serif').fontSize(14).fillColor(C.ink).text('Want more on choosing vendors?', PAGE.m, cTop, { width: W * 0.62 });
    doc.font('sans').fontSize(9.5).fillColor(C.body).text(clean(`This report is generated by ${config.brand.aiName}, an AI reviewer built by ${config.brand.ownerName}. ${config.brand.ownerName.split(' ')[0]} writes about choosing vendors and making technology decisions in the CTO notes.`), PAGE.m, doc.y + 4, { width: W * 0.62, lineGap: 2 });
    const afterText = doc.y;
    doc.font('sans').fontSize(9.5).fillColor(C.accent)
      .text(clean(notesUrl.replace(/^https?:\/\//, '')), PAGE.m + W * 0.66, cTop + 4, { width: W * 0.34, align: 'right', link: notesUrl, underline: true });
    doc.fillColor(C.body).text(clean(config.brand.contactEmail), PAGE.m + W * 0.66, doc.y + 2, { width: W * 0.34, align: 'right' });
    doc.y = Math.max(afterText, doc.y);

    /* Page numbers */
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      const keep = doc.page.margins.bottom;
      doc.page.margins.bottom = 0;
      doc.font('sans').fontSize(8).fillColor(C.muted)
        .text(`${clean(config.brand.aiName)} · Vendor quote review · Page ${i + 1} of ${range.count}`, PAGE.m, PAGE.h - 40, { width: W, align: 'center', lineBreak: false });
      doc.page.margins.bottom = keep;
    }
    doc.end();
  });
}

module.exports = { buildReportPdf };
